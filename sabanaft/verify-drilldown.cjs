assert.equal(bw.location.hash,'#overview');
bd.querySelector('.quick [data-bmc="value"]').click();
assert.equal(bw.location.hash,'#value','mobile block list uses same drilldown route');
assert.ok(bd.body.classList.contains('bm-detail-active'));
bw.close();
