'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {JSDOM}=require('jsdom'),read=p=>fs.readFileSync(path.join(__dirname,p),'utf8');
// Model stages: route to a new screen, then to an activity; never append the activity below the landing card.
const doc=new JSDOM(read('app/index.html'),{url:'https://example.test/sabanaft/app/',runScripts:'outside-only'});
const w=doc.window;w.scrollTo=()=>{};w.HTMLElement.prototype.scrollIntoView=()=>{};
w.eval(read('reflective-content.js'));w.eval(read('app/app.js'));
const d=w.document;
assert.equal(d.querySelectorAll('.saba-home-tile').length,4,'four original leadership components retained');
assert.equal(d.querySelectorAll('.saba-reflection-band').length,1,'continuous reflection remains a major fifth entry');
assert.ok(d.querySelector('link[href*="premium-v2.css"]'),'unified visual system loaded last');
assert.ok(d.querySelector('.topbar #modelNavToggle'),'menu control belongs to topbar, not floating over content');
assert.ok(d.querySelector('.topbar #globalScore'),'score belongs to topbar, not floating over content');
d.querySelector('[data-go="stage/idea"]').click();w.dispatchEvent(new w.HashChangeEvent('hashchange'));
assert.equal(w.location.hash,'#/stage/idea');
assert.ok(d.querySelector('#stageView.active'),'stage gets its own full screen');
assert.ok(!d.querySelector('#homeView.active'),'home is not appended under the stage');
assert.equal(d.querySelectorAll('#stageActionList button').length,3);
d.querySelector('[data-go-stage="lesson/5/mix"]').click();w.dispatchEvent(new w.HashChangeEvent('hashchange'));
assert.equal(w.location.hash,'#/lesson/5/mix');
assert.ok(d.querySelector('#readerView.active'),'lesson occupies an independent reader screen');
assert.ok(!d.querySelector('#stageView.active'),'stage is replaced by reader');
assert.ok(d.querySelector('.lesson-switch:not([open])'),'switching to another section is optional and collapsed');
d.querySelector('#readerBack').click();assert.equal(w.location.hash,'#/stage/idea','reader back returns to the originating model stage');
d.querySelector('[data-go="stage/reflection"]').click();w.dispatchEvent(new w.HashChangeEvent('hashchange'));
assert.ok(d.querySelector('#stageActionList [data-go-stage="studio/daily"]'));
d.querySelector('#stageBack').click();assert.equal(w.location.hash,'#/home');
w.close();
// Business model: clicking a block shows its own route and the overview is hidden by a dedicated state.
const b=new JSDOM(read('app/business-model.html'),{url:'https://example.test/sabanaft/app/business-model.html',runScripts:'outside-only'});
const bw=b.window;bw.scrollTo=()=>{};bw.HTMLElement.prototype.scrollIntoView=()=>{};
const scripts=[...read('app/business-model.html').matchAll(/<script>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,1);
bw.eval(scripts[0][1]);
const bd=bw.document;
assert.equal(bd.querySelectorAll('.canvas-block').length,9);
assert.ok(!bd.body.classList.contains('bm-detail-active'),'BMC starts with only overview');
bd.querySelector('.canvas-block[data-bmc="segments"]').click();
assert.equal(bw.location.hash,'#segments');
assert.ok(bd.body.classList.contains('bm-detail-active'),'details replace overview on their own screen');
assert.match(bd.querySelector('#detailTitle').textContent,/بخش‌های مشتری/);
assert.ok(bd.querySelector('#goOverviewTop'),'accessible top back control');
