/* Saba Naft chapter 1–5 navigation / visual hierarchy regression. */
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const read=p=>fs.readFileSync(path.join(__dirname,p),'utf8');
const html=read('app/index.html');
const d=new JSDOM(html,{url:'https://example.test/sabanaft/app/',runScripts:'outside-only'});
const w=d.window;w.scrollTo=()=>{};w.HTMLElement.prototype.scrollIntoView=()=>{};
const doc=w.document;
assert.equal(doc.querySelectorAll('#homeView .ch5-workspace').length,4,'home must have four clearly defined workspaces');
assert.equal(doc.querySelectorAll('#homeView #heroStart').length,1,'hero must offer one primary start');
assert.equal(doc.querySelectorAll('#homeView #futureCoachEntry').length,1,'case CTA retained');
assert.ok(doc.querySelector('#homeView [data-go="studio/daily"]'),'reflection one-tap route');
assert.ok(doc.querySelector('#homeView [data-go="studio/mix"]'),'leadership identity one-tap route');
assert.ok(doc.querySelector('#homeView [data-go="studio/development"]'),'IDP one-tap route');
assert.ok(doc.querySelector('#homeView details.ch5-resources'),'secondary resources tucked away');
assert.ok(doc.querySelector('#homeView details.ch5-resources #resume'),'resume preserved');
assert.ok(doc.querySelector('#homeView details.ch5-resources #homeCompleted'),'existing completion counter preserved');
assert.equal(doc.querySelectorAll('.bottom-nav [data-nav]').length,4,'four clear bottom navigation shortcuts');
assert.equal(doc.querySelectorAll('.bottom-nav [data-nav="studio/mix"]').length,1,'identity bottom nav is present');
assert.ok(doc.querySelector('link[href*="ch5-product-shell.css"]'),'new shell design stylesheet linked');
let sheet=read('app/ch5-product-shell.css');
assert.match(sheet,/#homeView \.ch5-workspaces/);
assert.match(sheet,/@media\(max-width:700px\)/);
assert.match(read('assets/ch5-studio-dashboard.css'),/\.ch5-studio-shortcuts/);
assert.match(read('leadership-studio.html'),/ch5-studio-dashboard.css/);
const sw=read('app/sw.js');
assert.match(sw,/sabanaft-reflective-pwa-shell-v10/);
assert.ok(sw.includes('./ch5-product-shell.css'),'new stylesheet cached offline');
w.eval(read('reflective-content.js'));
w.eval(read('app/app.js'));
doc.querySelector('#homeView [data-go="studio/mix"]').click();
assert.equal(w.location.hash,'#/studio/mix','identity route is navigable');
w.dispatchEvent(new w.HashChangeEvent('hashchange'));
assert.match(doc.getElementById('externalStudio').href,/#mix$/,'studio receives identity hash');
doc.querySelector('#homeView [data-go="studio/development"]').click();
assert.equal(w.location.hash,'#/studio/development','development route is navigable');
w.dispatchEvent(new w.HashChangeEvent('hashchange'));
assert.match(doc.getElementById('externalStudio').href,/#development$/,'studio receives development hash');
doc.querySelector('#homeView [data-go="studio/daily"]').click();
assert.equal(w.location.hash,'#/studio/daily','reflection remains accessible');
doc.querySelector('#homeView #futureCoachEntry').click();
assert.equal(w.location.hash,'#/coach','case-first desk remains available');
assert.match(doc.getElementById('homeView').textContent,/بوم کسب‌وکار/,'business-model link retained');
d.window.close();
console.log('PASS Saba chapter-5 dashboard: four workspaces, responsive CSS, accessible routes, retained resources and isolated cache');
