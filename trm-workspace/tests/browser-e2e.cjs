'use strict';
/* Real Chromium UX flow with fictional records ONLY. Never writes to a production backend. */
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const errors=[];
 const page=await browser.newPage({viewport:{width:1365,height:850},locale:'fa-IR',timezoneId:'Asia/Tehran'});
 page.on('pageerror',e=>errors.push(e.message));
 const root='http://127.0.0.1:8765/trm-workspace/';
 try{
  await page.goto(root,{waitUntil:'domcontentloaded'});
  await page.waitForSelector('.command-hero');
  assert(await page.locator('[data-go="agent"]').count()>0,'AI entry');
  assert(await page.locator('.command-tile').count()===4,'focused home');
  assert(await page.getByRole('heading',{name:'رابطه بسازید. استعداد جذب کنید.'}).isVisible(),'command hero');
  console.log('PASS clean TRM command center');
  await page.locator('.command-tile[data-go="roles"]').click();
  await page.locator('button[data-action="add-role"]').first().click();
  await page.locator('form[data-form="role"] [name="name"]').fill('مهندس توسعه آزمایشی');
  await page.locator('form[data-form="role"] [name="strategyEvidence"]').fill('توسعه محصول مصنوعی؛ داده صرفاً برای تست');
  await page.locator('form[data-form="role"] [name="challenges"]').fill('وقوع اختلال فرضی در طراحی محصول و مدیریت تضاد زمان و کیفیت');
  await page.locator('form[data-form="role"] [name="targetGroup"]').fill('مهندسان توسعه محصول');
  await page.locator('form[data-form="role"] button[type="submit"]').click();
  assert(await page.getByText('مهندس توسعه آزمایشی').first().isVisible(),'saved role visible');
  console.log('PASS critical role record');
  await page.locator('.nav-link[data-go="vacancies"]').click();
  await page.locator('button[data-action="add-vacancy"]').first().click();
  await page.locator('form[data-form="vacancy"] [name="reason"]').fill('توسعه نمونه ساختگی محصول');
  await page.locator('form[data-form="vacancy"] [name="owner"]').fill('مسئول آزمایشی');
  await page.locator('form[data-form="vacancy"] button[type="submit"]').click();
  assert(await page.getByText('توسعه نمونه ساختگی محصول').first().isVisible(),'vacancy card saved');
  console.log('PASS CRM vacancy pipeline');
  await page.locator('button[data-action="coach-vacancy"]').first().click();
  assert(await page.locator('#coach-form').isVisible(),'coach form');
  await page.locator('button[data-action="run-coach"]').click();
  assert((await page.locator('#coach-result').innerText()).includes('مهندس توسعه آزمایشی'),'recommendation uses role data');
  assert((await page.locator('#coach-result').innerText()).includes('Next Best Actions'),'action plan shown');
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('#coach-result [data-action="approve-coach-actions"]').click();
  assert(await page.getByRole('heading',{name:'برنامه اقدام TRM'}).isVisible(),'approved CRM tasks page');
  assert(await page.locator('.task-record').count()>0,'AI plan became assigned draft actions');
  await page.locator('.nav-link[data-go="agent"]').click();
  console.log('PASS vacancy activation plan uses real test records');
  await page.locator('.nav-link[data-go="evp"]').click();
  await page.locator('button[data-action="add-evp"]').first().click();
  await page.locator('form[data-form="evp"] [name="strengths"]').fill('مدیریت واقعی پروژه آزمایشی');
  await page.locator('form[data-form="evp"] [name="preferences"]').fill('اختیار بیشتر در توسعه محصول');
  await page.locator('button[data-action="generate-evp"]').click();
  assert((await page.locator('#evp-review-result').innerText()).includes('شاهد'),'missing EVP proof must be exposed');
  assert((await page.locator('form[data-form="evp"] [name="message"]').inputValue()).includes('فاقد شاهد'),'draft must not claim fully proven EVP');
  await page.locator('form[data-form="evp"] button[type="submit"]').click();
  console.log('PASS conditional evidence-based EVP');
  await page.reload({waitUntil:'domcontentloaded'});
  await page.waitForSelector('.logo');
  await page.locator('.nav-link[data-go="vacancies"]').click();
  assert(await page.getByText('توسعه نمونه ساختگی محصول').first().isVisible(),'role/vacancy persist after reload');
  console.log('PASS local persistence');
  await page.setViewportSize({width:390,height:844});
  await page.goto(root,{waitUntil:'domcontentloaded'});
  await page.waitForSelector('.command-grid');
  assert.equal(await page.locator('.command-tile').count(),4,'mobile quick actions');
  assert(await page.locator('.bottombar').isVisible(),'mobile navigation visible');
  assert.equal(await page.evaluate(()=>document.documentElement.dir),'rtl','RTL');
  assert((await page.evaluate(()=>document.documentElement.scrollWidth)) <= 410,'no significant horizontal overflow');
  console.log('PASS mobile 390px responsive');
  assert.deepEqual(errors,[],'uncaught browser errors');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
