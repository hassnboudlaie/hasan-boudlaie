/* My Finance Auth regression checks. No password, remote auth, user account or keys. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const base=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const source=readFileSync(resolve(base,'supabase-sync.js'),'utf8');
const prefix=source.slice(source.indexOf("const AUTH_SESSION_KEY="),source.indexOf("const client=createClient("));
assert.ok(prefix.includes('persist'), 'Auth persistence adapter missing');
const map=()=>({data:new Map(),getItem(k){return this.data.get(k)||null},setItem(k,v){this.data.set(k,String(v))},removeItem(k){this.data.delete(k)}});
const localStorage=map(),sessionStorage=map();
const auth=new Function('localStorage','sessionStorage',prefix+';return {AUTH_SESSION_KEY,KEEP_SIGNED_IN_KEY,financeAuthStorage,keepSignedIn};')(localStorage,sessionStorage);
const k=auth.AUTH_SESSION_KEY,r=auth.KEEP_SIGNED_IN_KEY;
assert.equal(auth.keepSignedIn(),true,'Remember-me must default to yes');
auth.financeAuthStorage.setItem(k,'synthetic-session-1');
assert.equal(localStorage.getItem(k),'synthetic-session-1');
assert.equal(sessionStorage.getItem(k),null);
auth.financeAuthStorage.setItem(k,'synthetic-session-2');
assert.equal(auth.financeAuthStorage.getItem(k),'synthetic-session-2','Page refresh must restore remembered token');
localStorage.setItem(r,'no');
auth.financeAuthStorage.setItem(k,'temporary-session');
assert.equal(localStorage.getItem(k),null,'Opt-out must not persist after browser close');
assert.equal(sessionStorage.getItem(k),'temporary-session');
localStorage.setItem(r,'yes');
assert.equal(auth.financeAuthStorage.getItem(k),'temporary-session','Opt-in must migrate a legitimate tab session');
assert.equal(localStorage.getItem(k),'temporary-session');
assert.equal(sessionStorage.getItem(k),null);
auth.financeAuthStorage.removeItem(k);
assert.equal(localStorage.getItem(k),null);
const helperStart=source.indexOf('function financeAuthFailureKind('),helperEnd=source.indexOf('async function refreshIdentity()',helperStart);
assert.ok(helperStart>=0&&helperEnd>helperStart,'First-visit classification missing');
const financeAuthFailureKind=new Function('navigator',source.slice(helperStart,helperEnd)+';return financeAuthFailureKind;')({onLine:true});
assert.equal(financeAuthFailureKind({name:'AuthSessionMissingError',message:'Auth session missing!'},false),'first-login');
assert.equal(financeAuthFailureKind({code:'email_not_confirmed',message:'Email not confirmed'},false),'unconfirmed');
assert.equal(financeAuthFailureKind({message:'Failed to fetch'},true),'network');
assert.equal(financeAuthFailureKind({message:'Invalid Refresh Token'},true),'expired');
assert.ok(source.includes("reason==='network'&&verifiedHere"),'Already verified user must retain session on temporary disconnect');
assert.ok(source.includes("storedSession?.user?.id===user.id"),'Only same identity may retain an unlocked view');
assert.ok(source.includes("Number(storedSession.expires_at||0)>Date.now()/1000"),'Previously verified token must still be unexpired');
assert.ok(!source.includes('ورود امن تأیید نشد. اتصال اینترنت را بررسی کنید'), 'Initial login message still blames internet');
assert.ok(source.includes('persistSession:true')&&source.includes('autoRefreshToken:true'),'Server-confirmed session persistence should be enabled');
console.log('PASS Auth: first sign-in, unconfirmed email, offline, expired token, opt-in/out and trusted-device session reuse');
