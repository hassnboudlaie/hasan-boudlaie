'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(root,'alborz-backend/index.ts'),'utf8');
const mirror=fs.readFileSync(path.join(root,'alborz-communication-skills/backend/alborz-workshop-sync.ts'),'utf8');
const migration=fs.readFileSync(path.join(root,'alborz-backend/teacher-session-rotation.sql'),'utf8');
assert.equal(source,mirror,'deployed and tracked edge function sources must match');
assert.match(source,/rpc\/alborz_rotate_teacher_session/,'instructor login must atomically rotate the existing teacher session');
assert.doesNotMatch(source,/await db\('alborz_access_keys',\{secret_hash:digest,access_role:'teacher'/,'instructor login must not INSERT a second active teacher key');
assert.match(source,/rpc\/alborz_verify_instructor_national/,'teacher role must still be verified server-side');
assert.match(source,/if\(body\.instructorView===true\)/,'an invalid instructor login must not consume a participant seat');
assert.match(source,/randomSession\(\);digest=await hash\(session\)/,'session token stays randomly generated and hashed');
assert.match(migration,/pg_advisory_xact_lock/,'teacher rotation must serialize concurrent logins');
assert.match(migration,/where access_role='teacher' and revoked=false/,'rotate only an existing active instructor session');
assert.match(migration,/security invoker/,'do not bypass RLS with a security-definer function');
assert.match(migration,/grant execute on function public\.alborz_rotate_teacher_session\(text,timestamptz\) to service_role/,'private session rotation callable by service role only');
console.log('PASS: instructor session rotation preserves single active session, private lookup, and participant capacity');
