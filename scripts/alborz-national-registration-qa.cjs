'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const edge=read('alborz-communication-skills/backend/alborz-workshop-sync.ts');
const entry=read('alborz-communication-skills/resilience-live.js');
const sql=read('alborz-backend/national-self-registration.sql');
const reset=read('alborz-backend/national-reset.sql');
const match=edge.match(/function validNational\(code\)\{[^\n]+/);
assert(match,'National-code checksum must be validated on the server');
const validate=new Function(match[0]+'; return validNational;')();
for(const c of ['1234567891','9876543210','0011234563'])assert(validate(c),'valid sample '+c);
for(const c of ['0000000000','1234567890','123456789','abcdefghij'])assert(!validate(c),'invalid input '+c);
assert(edge.includes("rpc/alborz_enroll_national"),'arrival enrollment must use atomic RPC');
assert(edge.includes("alborz_national_sessions"),'participant sessions must use national registration');
assert(!edge.includes("alborz_pin_sessions"),'legacy PIN sessions must not authenticate participants');
assert(edge.includes("&access_role=eq.teacher"),'legacy access token must be instructor-only');
assert(sql.includes('pg_advisory_xact_lock'),'concurrent enrollments must serialize');
assert(sql.includes('unique (team_no, member_no)'),'group seat allocation must be unique');
assert(sql.includes('enable row level security'),'national mapping must be protected by RLS');
assert(reset.includes('delete from public.alborz_national_members'),'clean start must clear test arrivals');
assert(entry.includes("teacher?24:10"),'participant input must accept ten-digit national code');
assert(!entry.includes('کد ۸ رقمی'),'no PIN in participant login');
console.log('PASS national-code checksum, atomic group assignment, session protection, instructor isolation and clean reset');
